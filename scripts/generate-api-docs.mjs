import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const sourcePath = resolve(root, 'src/baseClass.ts')
const sourceText = await readFile(sourcePath, 'utf8')

const declarationPattern = /export\s+(?:type|interface)\s+[A-Za-z_$][\w$]*/g
const matches = [...sourceText.matchAll(declarationPattern)]
const classStart = sourceText.indexOf('\nclass BaseClass')
const declarations = matches.map((match, index) => {
  const start = match.index
  const nextStart = matches[index + 1]?.index ?? classStart
  return sourceText.slice(start, nextStart).trim()
})

const declarationBlock = declarations.join('\n\n')
const pages = [
  {
    path: 'docs/api/generated.md',
    title: 'Type definitions',
    note: 'This page is generated from [src/baseClass.ts](https://github.com/ekworp/danmu.js/blob/main/src/baseClass.ts). Do not edit this file manually. Run `pnpm run docs:api` after changing the public types.'
  },
  {
    path: 'docs/zh/api/generated.md',
    title: '类型定义',
    note: '此页面由 [src/baseClass.ts](https://github.com/ekworp/danmu.js/blob/main/src/baseClass.ts) 自动生成。请勿手动编辑此文件。修改公开类型后运行 `pnpm run docs:api`。'
  }
]

for (const page of pages) {
  const outputPath = resolve(root, page.path)
  const output = `# ${page.title}

${page.note}

\`\`\`ts
${declarationBlock}
\`\`\`
`
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, output)
}
